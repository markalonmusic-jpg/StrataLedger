"""Build reference snapshots of the company and master schemas from migrations/*.sql.

migrations/*.sql are the schema source of truth. accounting_librebase.db is a
reference snapshot generated by this script, so the two cannot drift. It is
not read at runtime and must not be edited by hand.

Usage (from the project root):
    python scripts/build_reference_snapshot.py --out accounting_librebase.db --force
    python scripts/build_reference_snapshot.py --out C:\\temp\\company.db --master-out C:\\temp\\master.db

The databases are built in a temporary folder through the normal upgrade path
(database.ensure_*_database), verified with foreign_key_check and
integrity_check, and then written with VACUUM INTO. An existing output file is
only replaced with --force.
"""
import argparse
import os
import sqlite3
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import modules.database as database  # noqa: E402


def _build(kind, workdir):
    path = Path(workdir) / f"{kind}.db"
    if kind == "company":
        database.ensure_company_database(path)
    else:
        database.ensure_master_database(path)
    conn = sqlite3.connect(path)
    try:
        problems = database._verify_schema(conn)
    finally:
        conn.close()
    if problems:
        raise RuntimeError(f"{kind} schema failed verification: {problems}")
    return path


def _write(source, target, force):
    target = Path(target).resolve()
    if target.exists():
        if not force:
            raise FileExistsError(f"{target} exists; pass --force to replace it")
        target.unlink()
    target.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(source)
    try:
        conn.execute("VACUUM INTO ?", (os.fspath(target),))
    finally:
        conn.close()
    return target


def build_snapshots(out, master_out=None, force=False):
    with tempfile.TemporaryDirectory() as workdir:
        company = _build("company", workdir)
        master = _build("master", workdir)
        written = [_write(company, out, force)]
        if master_out:
            written.append(_write(master, master_out, force))
    return written


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, help="company snapshot path (e.g. accounting_librebase.db)")
    parser.add_argument("--master-out", help="optional master snapshot path")
    parser.add_argument("--force", action="store_true", help="replace existing output files")
    args = parser.parse_args(argv)
    for path in build_snapshots(args.out, args.master_out, args.force):
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
