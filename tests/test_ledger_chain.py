# --- what changes the hash, and what does not --------------------------------------------------------------

HEADER_CHANGES = {
    "entry_id": 99, "entry_number": 5, "entry_date": "2026-03-14", "period_id": 4, "reference": "R-2",
    "description": "Rent", "source": "Adjustment", "origin": "Agent", "created_by": 6,
    "created_at": "2026-03-15 08:00:01", "posted_by": 8, "posted_at": "2026-03-16 09:31:00", "approved_by": 8,
    "approved_at": "2026-03-16 09:31:00", "reverses_entry_id": 41, "reversal_reason": "Correction",
    "reversal_note": "why", "auto_reverse_date": "2026-04-01", "chain_version": 2, "chain_key_id": 2,
}


def test_header_changes_cover_every_hashed_field():
    assert set(HEADER_CHANGES) == set(lc.HASHED_ENTRY)


@pytest.mark.parametrize("field", lc.HASHED_ENTRY)
def test_every_hashed_header_field_changes_the_hash(field):
    vector = copy.deepcopy(E1)
    assert vector["header"][field] != HEADER_CHANGES[field]
    vector["header"][field] = HEADER_CHANGES[field]
    assert chain_hash(vector) != E1["chain_hash"]


def changed(value):
    return 1 if value is None else value + 1


@pytest.mark.parametrize("field", lc.HASHED_LINE)
def test_every_hashed_line_field_changes_the_hash(field):
    vector = copy.deepcopy(E1)
    line = vector["lines"][1]                            # line 101
    if field in ("memo", "external_ref"):
        line[field] = "changed" if line[field] is None else line[field] + "x"
    elif field.startswith("is_"):
        line[field] = 1 - line[field]
    elif field == "line_id":
        line[field] = 105
        for dim in vector["dimensions"]:
            dim["line_id"] = 105
    else:
        line[field] = changed(line[field])
    assert chain_hash(vector) != E1["chain_hash"]


@pytest.mark.parametrize("change", ["value", "type", "add", "remove"])
def test_every_dimension_change_changes_the_hash(change):
    vector = copy.deepcopy(E1)
    dims = vector["dimensions"]
    if change == "value":
        dims[0]["dimension_value_id"] += 1
    elif change == "type":
        dims[0]["dimension_type_id"] = 3
    elif change == "add":
        dims.append({"line_id": 102, "dimension_type_id": 1, "dimension_value_id": 4})
    else:
        dims.pop()
    assert chain_hash(vector) != E1["chain_hash"]


def test_adding_or_removing_a_line_changes_the_hash():
    removed = copy.deepcopy(E1)
    removed["lines"].pop(0)
    added = copy.deepcopy(E1)
    added["lines"].append({**added["lines"][0], "line_id": 110})
    assert chain_hash(removed) != E1["chain_hash"] and chain_hash(added) != E1["chain_hash"]


@pytest.mark.parametrize("where, field, value", [
    ("header", "is_void", 0),
    ("header", "is_posted", 0),
    ("header", "chain_hash", "f" * 64),
    ("header", "chain_prev_hash", "e" * 64),
    ("line", "recon_id", 77),
])
def test_excluded_fields_do_not_change_the_hash(where, field, value):
    vector = copy.deepcopy(E1)
    target = vector["header"] if where == "header" else vector["lines"][1]
    target[field] = value
    assert chain_hash(vector) == E1["chain_hash"]


# --- pure verification --------------------------------------------------------------------------------------

def sealed(vector, key, key_id, prev, number):
    entry = copy.deepcopy(vector)
    entry["header"].update(entry_number=number, chain_key_id=key_id, chain_prev_hash=prev)
    entry["header"]["chain_hash"] = lc.seal(key, CODE, prev, canon(entry))
    return entry


def test_the_golden_chain_verifies():
    result = lc.verify_chain(CODE, [E1, E2], {1: KEY}.__getitem__)
    assert result == {"ok": True, "through_entry_number": 2, "chain_hash": E2["chain_hash"], "first_broken": None}


def test_an_empty_ledger_verifies():
    assert lc.verify_chain(CODE, [], {}.__getitem__) == {
        "ok": True, "through_entry_number": 0, "chain_hash": None, "first_broken": None}


def test_entries_sealed_under_two_keys_verify_with_the_key_named_by_chain_key_id():
    key_a, key_b = bytes(range(32)), bytes(range(1, 33))
    first = sealed(E1, key_a, 1, lc.GENESIS, 1)
    second = sealed(E2, key_b, 2, first["header"]["chain_hash"], 2)
    keys = {1: key_a, 2: key_b}
    assert lc.verify_chain(CODE, [first, second], keys.__getitem__)["ok"] is True
    swapped = lc.verify_chain(CODE, [first, second], {1: key_b, 2: key_a}.__getitem__)
    assert swapped["ok"] is False and swapped["first_broken"]["entry_number"] == 1
    one_key = lc.verify_chain(CODE, [first, second], {1: key_a, 2: key_a}.__getitem__)
    assert one_key["first_broken"]["entry_number"] == 2 and one_key["through_entry_number"] == 1


def test_a_missing_key_is_reported_as_a_break():
    result = lc.verify_chain(CODE, [E1, E2], {}.__getitem__)
    assert result["ok"] is False and result["first_broken"]["entry_number"] == 1
    assert "key" in result["first_broken"]["reason"]


@pytest.mark.parametrize("tamper, broken_at", [
    ("line_amount", 1),
    ("second_header", 2),
    ("prev_link", 2),
    ("gap", 2),
    ("version", 1),
    ("stored_hash", 1),
])
def test_verification_names_the_first_broken_entry(tamper, broken_at):
    first, second = copy.deepcopy(E1), copy.deepcopy(E2)
    if tamper == "line_amount":
        first["lines"][0]["credit_cents"] += 1
    elif tamper == "second_header":
        second["header"]["description"] = "edited"
    elif tamper == "prev_link":
        second["header"]["chain_prev_hash"] = "a" * 64
    elif tamper == "gap":
        second["header"]["entry_number"] = 3
    elif tamper == "version":
        first["header"]["chain_version"] = 2
    elif tamper == "stored_hash":
        first["header"]["chain_hash"] = "b" * 64
    result = lc.verify_chain(CODE, [first, second], {1: KEY}.__getitem__)
    assert result["ok"] is False and result["first_broken"]["entry_number"] == broken_at
    assert result["through_entry_number"] == broken_at - 1


def test_verification_never_puts_the_key_in_its_result():
    result = lc.verify_chain(CODE, [E1, {**E2, "lines": []}], {1: KEY}.__getitem__)
    text = repr(result)
    assert KEY.hex() not in text and KEY.hex().upper() not in text


# --- every column is classified (static, against the baseline) ------------------------------------------------

@pytest.fixture
def conn(fresh_company):
    connection = database.get_connection(fresh_company)
    yield connection
    connection.close()


@pytest.mark.parametrize("table, hashed, excluded", [
    ("journal_entry", lc.HASHED_ENTRY, lc.EXCLUDED_ENTRY),
    ("journal_line", lc.HASHED_LINE, lc.EXCLUDED_LINE),
    ("journal_line_dimension", lc.HASHED_DIMENSION, lc.EXCLUDED_DIMENSION),
])
def test_every_journal_column_is_hashed_or_excluded(conn, table, hashed, excluded):
    columns = {row["name"] for row in conn.execute(f"PRAGMA table_info({table})")}
    assert not set(hashed) & set(excluded)
    assert set(hashed) | set(excluded) == columns, (
        f"classify every {table} column in ledger_chain.py (a new hashed field needs a new chain_version): "
        f"unclassified {sorted(columns - set(hashed) - set(excluded))}, unknown {sorted(set(hashed) | set(excluded) - columns)}")
